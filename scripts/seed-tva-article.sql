<h2>Întrebări frecvente despre TVA construcții 2026</h2>

<p><strong>Care este cota TVA pentru construcții în 2026?</strong><br>
Cota standard este 21%, aplicabilă pentru manoperă, materiale, proiectare și toate serviciile legate de construcții. Nu există cotă redusă specifică pentru servicii de construcții.</p>

<p><strong>Mai există TVA de 9% pentru locuințe în 2026?</strong><br>
Da, dar doar temporar, până la 31 iulie 2026, și numai dacă au fost îndeplinite condiții stricte: antecontract semnat înainte de 1 august 2025, avans minim 20% plătit înainte de 31 iulie 2025, locuință sub 120 mp și sub 600.000 lei fără TVA. Dacă lipsește o singură condiție, se aplică 21%.</p>

<p><strong>Ce TVA se aplică pe materialele de construcții?</strong><br>
Toate materialele de construcții (BCA, cărămidă, ciment, armătură, polistiren etc.) se taxează cu cota standard de 21%.</p>

<p><strong>Ce TVA se aplică pe manopera de construcții?</strong><br>
Manopera se facturează cu 21% TVA dacă executantul este înregistrat în scopuri de TVA. Dacă executantul este persoană fizică sau PFA sub plafonul de 395.000 lei cifră de afaceri, nu aplică TVA.</p>

<p><strong>De când s-a modificat TVA-ul standard în România?</strong><br>
TVA standard a crescut de la 19% la 21% începând cu 1 august 2025, prin Legea nr. 141/2025.</p>

<p><strong>Care este diferența financiară concretă între TVA 9% și 21% la o locuință?</strong><br>
Pe o locuință de 500.000 lei fără TVA: cu 9% plătești 545.000 lei total, cu 21% plătești 605.000 lei total. Diferența este de 60.000 lei (~12.000 euro).</p>

